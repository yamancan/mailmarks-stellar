// Writes a test-key approval email and its pinned key record into a folder, to try the prover (or its Docker image)
// by hand: node prover/scripts/make-test-email.js <dir>   ->  <dir>/approval.eml, <dir>/keys/mailmarks.test-test.json
// Test sender approver@mailmarks.test, so the DEV proving key is used. Never a real email.
import { lstatSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { testKey, approvalEmail } from '../src/testmail.js';
import { keyRecord } from '../src/prove.js';
import { buildSubject } from '../src/encode.js';

// The name does not start with "test-": node --test would run it as a test file.
if (!process.argv[2]) { console.error('Usage: node prover/scripts/make-test-email.js <dir>'); process.exit(2); }
const dir = resolve(process.env.INIT_CWD || process.cwd(), process.argv[2]);
const eml = join(dir, 'approval.eml');
const keyFile = join(dir, 'keys', 'mailmarks.test-test.json');
if ([eml, keyFile].some((path) => lstatSync(path, { throwIfNoEntry: false }))) {
  console.error('A test email or key file already exists. Choose another folder.');
  process.exit(1);
}
const key = testKey();
const fields = { projectId: 'mailmarks', artifactSha256: 'bd043655bf8a1a2e2c1a9d21f1892b8cb6dc04b9d84e52fa2b986917e02a41ac', wallet: 'GA4TZT44MM6G4JHK4AFSHGDMXSHW3XJLLOEWCSBPA7LCPUT6FYXEX2KN' };
const rec = await keyRecord({ domain: 'mailmarks.test', selector: 'test', txt: key.record, fetched: new Date().toISOString().slice(0, 10), source: 'test key generated by prover/scripts/make-test-email.js' });
mkdirSync(join(dir, 'keys'), { recursive: true });
writeFileSync(keyFile, JSON.stringify(rec, null, 2) + '\n', { flag: 'wx' });
writeFileSync(eml, approvalEmail({ from: 'Approver <approver@mailmarks.test>', to: 'recipient@mailmarks.test',
  subject: buildSubject(fields), domain: 'mailmarks.test', selector: 'test', privateKey: key.privateKey }), { flag: 'wx', mode: 0o600 });
console.log('wrote ' + eml + ' and ' + keyFile);
